import json
import os

with open('src/data/students_seed.json', 'r', encoding='utf-8') as f:
    students = json.load(f)

subjects = [
    (1, 'Web Development', 'Assignment 1: Portfolio Webpage', 'Nov 15, 2026'),
    (2, 'English', 'Assignment 1: Technical Report Writing', 'Nov 18, 2026'),
    (3, 'Math', 'Assignment 1: Linear Algebra Problem Set', 'Nov 20, 2026'),
    (4, 'Physics', 'Assignment 1: Semiconductor Physics', 'Nov 22, 2026'),
    (5, 'C Language', 'Assignment 1: Pointers & Dynamic Memory', 'Nov 25, 2026'),
]

os.makedirs('supabase', exist_ok=True)

sql = []
sql.append('-- ============================================================')
sql.append('-- CR Assignment Tracker - Supabase SQL Schema & Initial Seed')
sql.append('-- Class: AIML Batch 1 (60 Students, 5 Subjects)')
sql.append('-- Run this in the Supabase Dashboard -> SQL Editor')
sql.append('-- ============================================================')
sql.append('')
sql.append('-- 1. Drop existing tables if re-running script')
sql.append('DROP TABLE IF EXISTS activity_logs CASCADE;')
sql.append('DROP TABLE IF EXISTS submissions CASCADE;')
sql.append('DROP TABLE IF EXISTS subjects CASCADE;')
sql.append('DROP TABLE IF EXISTS students CASCADE;')
sql.append('')
sql.append('-- 2. Create tables')
sql.append('CREATE TABLE students (')
sql.append('    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),')
sql.append('    sno INTEGER NOT NULL,')
sql.append('    name TEXT NOT NULL,')
sql.append('    roll_number TEXT NOT NULL UNIQUE,')
sql.append('    created_at TIMESTAMPTZ DEFAULT NOW()')
sql.append(');')
sql.append('')
sql.append('CREATE TABLE subjects (')
sql.append('    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),')
sql.append('    name TEXT NOT NULL UNIQUE,')
sql.append('    assignment_title TEXT DEFAULT \'\',')
sql.append('    due_date TEXT DEFAULT \'\',')
sql.append('    order_index INTEGER NOT NULL,')
sql.append('    created_at TIMESTAMPTZ DEFAULT NOW()')
sql.append(');')
sql.append('')
sql.append('CREATE TABLE submissions (')
sql.append('    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),')
sql.append('    student_id UUID NOT NULL REFERENCES students(id) ON DELETE CASCADE,')
sql.append('    subject_id UUID NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,')
sql.append('    submitted BOOLEAN NOT NULL DEFAULT FALSE,')
sql.append('    updated_at TIMESTAMPTZ DEFAULT NOW(),')
sql.append('    updated_by TEXT DEFAULT NULL,')
sql.append('    CONSTRAINT unique_student_subject UNIQUE(student_id, subject_id)')
sql.append(');')
sql.append('')
sql.append('CREATE TABLE activity_logs (')
sql.append('    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),')
sql.append('    description TEXT NOT NULL,')
sql.append('    created_at TIMESTAMPTZ DEFAULT NOW()')
sql.append(');')
sql.append('')
sql.append('-- 3. Enable Row Level Security (RLS)')
sql.append('ALTER TABLE students ENABLE ROW LEVEL SECURITY;')
sql.append('ALTER TABLE subjects ENABLE ROW LEVEL SECURITY;')
sql.append('ALTER TABLE submissions ENABLE ROW LEVEL SECURITY;')
sql.append('ALTER TABLE activity_logs ENABLE ROW LEVEL SECURITY;')
sql.append('')
sql.append('-- 4. RLS Policies: Public can read everything; Only authenticated CR can write')
sql.append('CREATE POLICY "Public can read students" ON students FOR SELECT USING (true);')
sql.append('CREATE POLICY "Public can read subjects" ON subjects FOR SELECT USING (true);')
sql.append('CREATE POLICY "Public can read submissions" ON submissions FOR SELECT USING (true);')
sql.append('CREATE POLICY "Public can read activity_logs" ON activity_logs FOR SELECT USING (true);')
sql.append('')
sql.append('CREATE POLICY "Auth admin can insert students" ON students FOR INSERT TO authenticated WITH CHECK (true);')
sql.append('CREATE POLICY "Auth admin can update students" ON students FOR UPDATE TO authenticated USING (true);')
sql.append('CREATE POLICY "Auth admin can delete students" ON students FOR DELETE TO authenticated USING (true);')
sql.append('')
sql.append('CREATE POLICY "Auth admin can insert subjects" ON subjects FOR INSERT TO authenticated WITH CHECK (true);')
sql.append('CREATE POLICY "Auth admin can update subjects" ON subjects FOR UPDATE TO authenticated USING (true);')
sql.append('CREATE POLICY "Auth admin can delete subjects" ON subjects FOR DELETE TO authenticated USING (true);')
sql.append('')
sql.append('CREATE POLICY "Auth admin can insert submissions" ON submissions FOR INSERT TO authenticated WITH CHECK (true);')
sql.append('CREATE POLICY "Auth admin can update submissions" ON submissions FOR UPDATE TO authenticated USING (true);')
sql.append('CREATE POLICY "Auth admin can delete submissions" ON submissions FOR DELETE TO authenticated USING (true);')
sql.append('')
sql.append('CREATE POLICY "Auth admin can insert logs" ON activity_logs FOR INSERT TO authenticated WITH CHECK (true);')
sql.append('')
sql.append('-- 5. Realtime replication setup')
sql.append('DO $$')
sql.append('BEGIN')
sql.append('    IF NOT EXISTS (SELECT 1 FROM pg_publication WHERE pubname = \'supabase_realtime\') THEN')
sql.append('        CREATE PUBLICATION supabase_realtime;')
sql.append('    END IF;')
sql.append('END $$;')
sql.append('ALTER PUBLICATION supabase_realtime ADD TABLE submissions;')
sql.append('ALTER PUBLICATION supabase_realtime ADD TABLE subjects;')
sql.append('ALTER PUBLICATION supabase_realtime ADD TABLE activity_logs;')
sql.append('')
sql.append('-- 6. Seed Subjects')
sql.append('INSERT INTO subjects (name, assignment_title, due_date, order_index) VALUES')
subj_rows = []
for idx, name, title, due in subjects:
    clean_title = title.replace("'", "''")
    subj_rows.append(f"    ('{name}', '{clean_title}', '{due}', {idx})")
sql.append(',\n'.join(subj_rows) + ';')
sql.append('')
sql.append('-- 7. Seed 60 Students (Without Emails for Privacy)')
sql.append('INSERT INTO students (sno, name, roll_number) VALUES')
stu_rows = []
for s in students:
    clean_name = s['name'].replace("'", "''")
    stu_rows.append(f"    ({s['sno']}, '{clean_name}', '{s['roll_number']}')")
sql.append(',\n'.join(stu_rows) + ';')
sql.append('')
sql.append('-- 8. Initialize Submissions (all false initially for all 60 students x 5 subjects = 300 rows)')
sql.append('INSERT INTO submissions (student_id, subject_id, submitted)')
sql.append('SELECT s.id, sub.id, FALSE')
sql.append('FROM students s')
sql.append('CROSS JOIN subjects sub;')
sql.append('')
sql.append('-- 9. Initial Activity Log')
sql.append("INSERT INTO activity_logs (description) VALUES ('Database initialized with 60 students and 5 subjects for AIML Batch 1');")

with open('supabase/schema.sql', 'w', encoding='utf-8') as f:
    f.write('\n'.join(sql) + '\n')

print('Generated supabase/schema.sql successfully')
